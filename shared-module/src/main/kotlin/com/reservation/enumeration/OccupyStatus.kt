package com.reservation.enumeration

/**
 * 좌석 점유의 생애.
 *
 * 예약이 즉시 확정되지 않고 [PENDING]을 거치는 이유는, 좌석을 잡는 것과 그 좌석을 쓰겠다고
 * 확정하는 것이 사용자에게 서로 다른 행위이기 때문이다. 잡아만 두고 사라지는 사용자가 좌석을
 * 영원히 묶지 않도록, 확정되지 않은 홀드는 일정 시간이 지나면 스케줄러가 회수한다.
 */
enum class OccupyStatus {
    /** 좌석을 잡았지만 아직 확정하지 않았다. 시간이 지나면 자동으로 취소된다. */
    PENDING,

    /** 사용자가 확정했다. 이 시점에 하류(예약 생성)로 도메인 이벤트가 나간다. */
    CONFIRMED,

    /**
     * 홀드 흐름 도입 이전에 쓰이던 "확정 점유". 기존 데이터를 읽기 위해 남겨 둔다.
     * 새로 만들어지는 점유는 [PENDING]에서 시작해 [CONFIRMED]로 간다.
     */
    OCCUPIED,

    UNOCCUPIED,
}

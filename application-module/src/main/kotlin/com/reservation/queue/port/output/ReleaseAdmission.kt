package com.reservation.queue.port.output

import com.reservation.queue.vo.WaitingQueueSlot

/**
 * 다 쓴 입장 자리를 대기열에 돌려준다.
 *
 * ## 왜 필요한가
 *
 * 입장 정원(`admission-capacity`)은 "동시에 예약 화면에 들어와 있을 수 있는 사람 수"다.
 * 예약을 마친 사용자는 그 자리를 차지할 이유가 없는데, 명시적으로 돌려주지 않으면 permit의
 * lease가 만료될 때까지(기본 5분) 자리가 묶인다. 30초면 끝날 사람이 5분치 자리를 쓰는 셈이라,
 * 정원이 100이어도 실제 회전은 그보다 훨씬 느려진다. 부하 시험에서 상당수 사용자가 끝내 입장하지
 * 못한 것도 이 때문이다.
 *
 * ## 언제 부르는가 — 기준은 성공/실패가 아니라 "재시도 여지"다
 *
 * 이 호출은 입장 자격 자체를 회수한다. 되돌린 뒤에는 게이트가 그 사용자를 거절하므로, 재시도할
 * 여지가 있는 실패(예: 발행 실패 같은 일시적 인프라 문제)에서 부르면 사용자가 자기 잘못도 아닌
 * 이유로 대기열 맨 뒤로 밀린다. 그런 실패에서는 부르지 않고 lease 만료에 맡긴다.
 *
 * 반대로 **종착 거절에서는 반드시 불러야 한다.** 품절·중복처럼 같은 슬롯에 다시 시도해도 결과가
 * 같은 경우, 자격을 붙들고 있어 봐야 그 사용자에게는 쓸모가 없고 뒤에 줄 선 사람의 자리만 막는다.
 *
 * 이건 이론이 아니라 실측으로 확인된 사항이다. 성공 경로에서만 되돌리던 시절, 정원 100짜리
 * 대기열이 VU 300이든 3,000이든 **누적 130명만 통과시키고 멈췄다** — 정원 100에 성공한 30명이
 * 돌려준 몫을 더한 값에서, 거절당한 70명이 자리를 쥔 채 끝나 회전이 죽었기 때문이다.
 *
 * ## 실패해도 조용히 넘어간다
 *
 * 되돌리기에 실패해도 lease가 만료되며 결국 회수된다. 여기서 예외를 던지면 이미 성공한 예약이
 * 실패로 뒤집힌다 — 정리 작업이 본 작업을 무너뜨려서는 안 된다.
 */
interface ReleaseAdmission {
    fun release(
        slot: WaitingQueueSlot,
        userId: String,
    )
}
